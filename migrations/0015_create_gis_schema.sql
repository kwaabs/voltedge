-- 0015_create_gis_schema.sql
-- Purpose: reserve the 'gis' schema -- where the schema compiler creates
-- physical tables for compiled feature classes (e.g. gis.pole,
-- gis.mv_conductor). Separate from metadata (the compiler's own
-- definitional tables) and ops (infra bookkeeping), same
-- separate-schema-per-concern principle as migrations 0001 and 0003.
-- Empty until the compiler actually compiles a feature class.
--
-- Also enables PostGIS: the generated `geometry` columns don't exist as
-- a type until this extension is loaded. supabase/postgres bundles
-- PostGIS but doesn't enable it by default.

CREATE EXTENSION IF NOT EXISTS postgis;

CREATE SCHEMA IF NOT EXISTS gis;

COMMENT ON SCHEMA gis IS 'Physical tables generated by the schema compiler from metadata.feature_classes -- one table per compiled feature class. Never hand-edited; DDL here is always generated, applied by api/internal/compiler.';
